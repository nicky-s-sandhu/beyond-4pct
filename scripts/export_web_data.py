"""Export the data the static dashboard (docs/dashboard/) needs: annual returns and inflation 1928-2025,
survival weights, the presets and the reshuffled-history (block bootstrap) year indices.

    python scripts/export_web_data.py
"""
from __future__ import annotations

import base64
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "app"))
from bengen import alt, data, vec  # noqa: E402
import model  # noqa: E402

OUT = ROOT / "docs" / "dashboard" / "data.json"


def main():
    base = data.load(intl_series="intl")
    stress = data.load(intl_series="intl_stress")
    years = [int(y) for y in base.index]
    r = lambda s: [float(v) for v in s]
    idx = alt.bootstrap_index(len(years), 5000, model.HORIZON, 10, 7)
    assert idx.max() < 256
    payload = {
        "note": "Generated by scripts/export_web_data.py. International series 1928-69 derived from the "
                "Jorda-Schularick-Taylor Macrohistory Database (CC BY-NC-SA 4.0); see the repository.",
        "years": years,
        "stocks": r(base["stocks"]), "bonds10y": r(base["bonds"]), "bills": r(base["bills"]),
        "inflation": r(base["inflation"]), "intl": r(base["intl"]), "intl_stress": r(stress["intl"]),
        "weights": {w: [round(float(v), 8) for v in vec.survival_weights(model.HORIZON, who=w)]
                    for w in ("couple", "single", "none")},
        "boot": {"n": int(idx.shape[0]), "T": int(idx.shape[1]), "block": 10, "seed": 7,
                 "idx_b64": base64.b64encode(idx.astype(np.uint8).tobytes()).decode()},
        "recommended": model.RECOMMENDED,
        "presets": model.PRESETS,
        "max_run_out": model.MAX_RUN_OUT,
    }
    OUT.write_text(json.dumps(payload, separators=(",", ":")))
    print(OUT, OUT.stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()
